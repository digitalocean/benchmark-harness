CREATE TABLE IF NOT EXISTS benchmark_runs (
  id CHAR(36) NOT NULL,
  benchmark VARCHAR(64) NOT NULL,
  model VARCHAR(191) NOT NULL,
  base_url VARCHAR(2048) NOT NULL,
  status VARCHAR(32) NOT NULL,
  started_at DATETIME(3) NOT NULL,
  finished_at DATETIME(3) NULL,
  cancel_requested_at DATETIME(3) NULL,
  exit_code INT NULL,
  epochs SMALLINT UNSIGNED NOT NULL,
  concurrency SMALLINT UNSIGNED NOT NULL,
  row_limit SMALLINT UNSIGNED NULL,
  range_start SMALLINT UNSIGNED NULL,
  range_end SMALLINT UNSIGNED NULL,
  max_retries SMALLINT UNSIGNED NULL,
  temperature DECIMAL(4, 3) NOT NULL,
  max_tokens INT UNSIGNED NULL,
  reasoning_effort VARCHAR(32) NULL,
  timeout_ms INT UNSIGNED NULL,
  endpoint_id VARCHAR(255) NULL,
  cost_tier VARCHAR(32) NULL,
  provider_sort VARCHAR(32) NULL,
  cloudflare_version VARCHAR(255) NULL,
  cost_quality_tradeoff SMALLINT UNSIGNED NULL,
  pin_model BOOLEAN NULL,
  log_level VARCHAR(32) NULL,
  upload_status VARCHAR(32) NOT NULL,
  upload_error TEXT NULL,
  uploaded_at DATETIME(3) NULL,
  spaces_bucket VARCHAR(255) NULL,
  spaces_prefix VARCHAR(1024) NULL,
  manifest_key VARCHAR(1024) NULL,
  args_json JSON NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
    ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  INDEX idx_benchmark_runs_started_at (started_at),
  INDEX idx_benchmark_runs_status (status),
  INDEX idx_benchmark_runs_model (model),
  INDEX idx_benchmark_runs_upload_status (upload_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
